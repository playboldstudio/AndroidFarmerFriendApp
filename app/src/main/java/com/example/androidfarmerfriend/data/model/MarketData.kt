    val allMarkets: List<MarketOption> = majorMarkets + states + cities

    fun marketsForCategory(filter: FilterType): List<MarketOption> {
        return when (filter) {
            FilterType.VEGETABLES -> allMarkets.filter { it.supportsVegetables }
            FilterType.FRUITS -> allMarkets.filter { it.supportsFruits }
            FilterType.NONVEG -> allMarkets.filter { it.supportsNonVeg }
            FilterType.GOLD -> allMarkets // Gold available everywhere via this API
            FilterType.EGG -> allMarkets // Egg has its own API
        }
    }

    fun defaultMarketForCategory(filter: FilterType): MarketOption {
        return when (filter) {
            FilterType.VEGETABLES -> majorMarkets.first { it.apiSlug == "koyambedu" }
            FilterType.FRUITS -> majorMarkets.first { it.apiSlug == "koyambedu" }
            FilterType.NONVEG -> majorMarkets.first { it.apiSlug == "bangalore" }
            FilterType.GOLD -> majorMarkets.first { it.apiSlug == "chennai" }
            FilterType.EGG -> majorMarkets.first { it.apiSlug == "chennai" }
        }
    }

    fun findMarket(slug: String): MarketOption? {
        return allMarkets.find { it.apiSlug == slug }
    }
