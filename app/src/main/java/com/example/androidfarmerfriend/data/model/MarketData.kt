enum class MarketGroup { MAJOR_MARKETS, STATES, CITIES }

data class MarketOption(
    val displayName: String,
    val apiSlug: String,
    val group: MarketGroup,
    val supportsVegetables: Boolean = true,
    val supportsFruits: Boolean = false,
    val supportsNonVeg: Boolean = false
) {
    fun supportsCategory(filter: FilterType): Boolean = when (filter) {
        FilterType.VEGETABLES -> supportsVegetables
        FilterType.FRUITS -> supportsFruits
        FilterType.NONVEG -> supportsNonVeg
        FilterType.GOLD -> true
        FilterType.EGG -> true
    }
}

